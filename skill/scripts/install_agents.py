#!/usr/bin/env python3
"""Install the skill's subagent roles (agents/*.md, the single source of truth) for Claude Code and Codex.

  Claude Code → ~/.claude/agents/<name>.md   (frontmatter minus codex_* keys)
  Codex       → ~/.codex/agents/<name>.toml  (name, description, developer_instructions, sandbox_mode,
                                               model_reasoning_effort; model inherits from the parent)

Re-run after editing any file in agents/. Only files carrying the "generated by metodologia" marker are
overwritten, so hand-made agents with the same name are never clobbered (use --force to override).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "agents"
CLAUDE_DIR = Path.home() / ".claude" / "agents"
CODEX_DIR = Path.home() / ".codex" / "agents"
MARKER = "generated by metodologia/scripts/install_agents.py — edit the source in the skill's agents/ folder"


def parse(f: Path) -> tuple[dict, list[str], str]:
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", f.read_text(encoding="utf-8"), re.S)
    if not m:
        raise SystemExit(f"{f.name}: missing frontmatter")
    lines = m.group(1).splitlines()
    meta = {k.strip(): v.strip() for k, v in (l.split(":", 1) for l in lines if ":" in l)}
    return meta, lines, m.group(2).strip() + "\n"


def can_write(target: Path, force: bool) -> bool:
    if not target.exists() or force:
        return True
    return MARKER in target.read_text(encoding="utf-8")


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--only", choices=["claude", "codex"])
    ap.add_argument("--claude-dir", action="append", type=Path, help="agents dir (repeatable); default ~/.claude/agents")
    ap.add_argument("--codex-dir", action="append", type=Path, help="agents dir (repeatable); default ~/.codex/agents")
    a = ap.parse_args()
    for f in sorted(SRC.glob("*.md")):
        meta, lines, body = parse(f)
        name = meta["name"]
        for claude_dir in (a.claude_dir or [CLAUDE_DIR]) if a.only != "codex" else []:
            claude_dir.mkdir(parents=True, exist_ok=True)
            target = claude_dir / f"{name}.md"
            if can_write(target, a.force):
                front = "\n".join(l for l in lines if not l.startswith("codex_"))
                target.write_text(f"---\n{front}\n---\n<!-- {MARKER} -->\n\n{body}", encoding="utf-8")
                print(f"claude: {target}")
            else:
                print(f"claude: SKIP {target} (not ours; --force to overwrite)", file=sys.stderr)
        for codex_dir in (a.codex_dir or [CODEX_DIR]) if a.only != "claude" else []:
            codex_dir.mkdir(parents=True, exist_ok=True)
            target = codex_dir / f"{name}.toml"
            if "'''" in body:
                raise SystemExit(f"{f.name}: body can't contain ''' (TOML literal delimiter)")
            if can_write(target, a.force):
                toml = [f"# {MARKER}", f"name = {toml_str(name)}", f"description = {toml_str(meta['description'])}"]
                if meta.get("codex_sandbox"):
                    toml.append(f"sandbox_mode = {toml_str(meta['codex_sandbox'])}")
                if meta.get("codex_effort"):
                    toml.append(f"model_reasoning_effort = {toml_str(meta['codex_effort'])}")
                toml.append(f"developer_instructions = '''\n{body}'''")
                target.write_text("\n".join(toml) + "\n", encoding="utf-8")
                print(f"codex:  {target}")
            else:
                print(f"codex:  SKIP {target} (not ours; --force to overwrite)", file=sys.stderr)


if __name__ == "__main__":
    main()
