"""Hourly quota sampling through a user systemd timer; never starts a model session."""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from bt_core import ROOT, SCRIPT

NAME = "metodologia-subscription-usage"
MARKER = "# Generated by metodologia subscription usage collector"


def unit_quote(value: str | Path, expand_env: bool = False) -> str:
    value = str(value)
    if "\n" in value or "\r" in value or "\x00" in value:
        raise ValueError("Unit values must be single-line strings")
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return '"' + (value.replace("$", "$$") if expand_env else value) + '"'


def render() -> tuple[str, str]:
    service = (f"{MARKER}\n[Unit]\nDescription=Metodologia subscription usage (no inference)\n"
               "[Service]\nType=oneshot\nTimeoutStartSec=300\nUMask=0077\n"
               f"Environment={unit_quote('BITACORA_ROOT=' + str(ROOT))}\n"
               f"Environment={unit_quote('PATH=' + os.environ.get('PATH', os.defpath))}\n"
               f"WorkingDirectory={str(SCRIPT.parent).replace('%', '%%')}\n"
               f"ExecStart={unit_quote(sys.executable, True)} {unit_quote(SCRIPT, True)} usage poll\n")
    timer = (f"{MARKER}\n[Unit]\nDescription=Hourly subscription usage sampling\n"
             "[Timer]\nOnCalendar=hourly\nPersistent=true\nAccuracySec=60\nRandomizedDelaySec=60\n"
             f"Unit={NAME}.service\n[Install]\nWantedBy=timers.target\n")
    return service, timer


def install() -> dict:
    if not sys.platform.startswith("linux") or not shutil.which("systemctl"):
        raise RuntimeError("Hourly installation requires user systemd; usage poll/show remain portable")
    base = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "systemd/user"
    targets = [base / (NAME + suffix) for suffix in (".service", ".timer")]
    for path in targets:
        if path.exists() and MARKER not in path.read_text(encoding="utf-8"):
            raise RuntimeError(f"Refusing to replace an unmanaged unit: {path.name}")
    contents = render()
    base.mkdir(parents=True, exist_ok=True)
    for path, content in zip(targets, contents):
        path.write_text(content, encoding="utf-8")
        path.chmod(0o600)
    subprocess.run(["systemctl", "--user", "daemon-reload"], check=True, capture_output=True, timeout=15)
    subprocess.run(["systemctl", "--user", "enable", "--now", NAME + ".timer"],
                   check=True, capture_output=True, timeout=15)
    return {"timer": NAME + ".timer", "interval": "hourly", "units": [str(p) for p in targets]}


def status() -> dict:
    if not sys.platform.startswith("linux") or not shutil.which("systemctl"):
        return {"status": "unsupported_scheduler"}
    result = subprocess.run(["systemctl", "--user", "show", NAME + ".timer", "--property=ActiveState",
                             "--property=NextElapseUSecRealtime", "--property=LastTriggerUSec"],
                            capture_output=True, text=True, timeout=15, check=False)
    if result.returncode:
        return {"status": "timer_unavailable"}
    return dict(line.split("=", 1) for line in result.stdout.splitlines() if "=" in line)
