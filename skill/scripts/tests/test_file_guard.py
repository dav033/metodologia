"""file_guard against real git repositories and real shell writes (REQ-030 item 8): the PostToolUse hook after a
shell command, its per-session memory, and the pure snapshot check the durable runtime runs at capture time."""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
GUARD = SCRIPTS / "file_guard.py"
sys.path.insert(0, str(SCRIPTS))

import file_guard


def lines(prefix: str, n: int) -> str:
    return "".join(f"{prefix} = {i}\n" for i in range(n))


class GuardCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="file-guard-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.env = {**os.environ, "HOME": str(self.tmp / "home"), "XDG_CACHE_HOME": str(self.tmp / "cache"),
                    "GIT_CEILING_DIRECTORIES": str(self.tmp), "GIT_AUTHOR_NAME": "T", "GIT_AUTHOR_EMAIL": "t@t",
                    "GIT_COMMITTER_NAME": "T", "GIT_COMMITTER_EMAIL": "t@t", "GIT_CONFIG_GLOBAL": os.devnull}
        self.repo = self.repository("app", {
            "grow.py": lines("x", 400), "sed.py": lines("s", 300), "big.py": lines("y", 900),
            "already.py": lines("a", 900), "small.py": lines("m", 100), "edge.py": lines("e", 499),
            "template.txt": lines("t", 650), "notes.md": "hello\n"})

    def git(self, cwd: Path, *args: str) -> str:
        done = subprocess.run(["git", "-c", "core.hooksPath=/dev/null", *args], cwd=cwd, env=self.env,
                              capture_output=True, text=True, check=False)
        self.assertEqual(done.returncode, 0, done.stderr)
        return done.stdout.strip()

    def repository(self, name: str, files: dict[str, str]) -> Path:
        repo = self.tmp / name
        repo.mkdir(parents=True)
        self.git(repo, "init", "-q", "-b", "main")
        for rel, text in files.items():
            (repo / rel).parent.mkdir(parents=True, exist_ok=True)
            (repo / rel).write_text(text, encoding="utf-8")
        self.git(repo, "add", "-A")
        self.git(repo, "commit", "-q", "--allow-empty", "-m", "base")
        return repo

    def sh(self, command: str, cwd: Path | None = None) -> None:
        done = subprocess.run(["bash", "-c", command], cwd=cwd or self.repo, env=self.env, capture_output=True,
                              text=True, check=False)
        self.assertEqual(done.returncode, 0, done.stderr)

    def hook(self, payload: dict | str, cwd: Path | None = None) -> subprocess.CompletedProcess:
        if isinstance(payload, dict):
            payload = json.dumps({"session_id": "s-1", "cwd": str(cwd or self.repo), "hook_event_name": "PostToolUse",
                                  **payload})
        return subprocess.run([sys.executable, str(GUARD)], input=payload, capture_output=True, text=True,
                              env=self.env, timeout=30, check=False)

    def bash(self, command: str, cwd: Path | None = None, session: str = "s-1") -> str:
        """Run a real shell write, then the hook for it; returns the advisory text ("" when silent)."""
        self.sh(command, cwd)
        done = self.hook({"tool_name": "Bash", "tool_input": {"command": command}, "session_id": session}, cwd)
        self.assertEqual(done.returncode, 0, done.stderr)
        if not done.stdout.strip():
            return ""
        output = json.loads(done.stdout)["hookSpecificOutput"]
        self.assertEqual(output["hookEventName"], "PostToolUse")
        return output["additionalContext"]


class ShellWrites(GuardCase):
    def test_reports_exactly_the_files_shell_writes_pushed_over_the_limit(self) -> None:
        writes = (
            "printf 'x = 2\\n%.0s' $(seq 200) >> grow.py",                              # 400 -> 600, crossed
            "sed -i 's/^s = \\(.*\\)$/s = \\1\\nt = \\1/' sed.py",                        # 300 -> 600, crossed
            "python3 -c \"open('made.py', 'w').write('v = 1\\n' * 700)\"",                # new untracked
            "cp template.txt copied.py",                                                  # new by copy
            "mkdir -p pkg/sub && seq 520 | sed 's/^/export const n = /' > pkg/sub/mod.ts",  # new dir, new file
            "printf 'm = 1\\n%.0s' $(seq 300) >> small.py",                               # 100 -> 400, within
            "printf 'e = 1\\n' >> edge.py",                                               # 499 -> 500, within
            "sed -i 's/^y = 1$/y = 100/' big.py",                                         # over at HEAD, same size
            # not source: lock, data, generated by name, by folder and by header, vendored
            "seq 3000 > package-lock.json && seq 3000 > uv.lock && seq 3000 > data.csv",
            "seq 900 | sed 's/^/x/' > api.generated.ts && mkdir -p generated node_modules/m",
            "seq 900 | sed 's/^/x = /' > generated/out.py && seq 900 > node_modules/m/index.js",
            "{ echo '# @generated by protoc'; seq 900 | sed 's/^/x = /'; } > schema_pb.py",
            "seq 900 | sed 's/^/x = /' > notes_test.py",
        )
        for command in writes:
            self.sh(command)
        found = file_guard.shell_findings(self.repo, "true", set())
        self.assertEqual({f["path"]: (f["kind"], f["base_lines"], f["lines"]) for f in found}, {
            "grow.py": ("crossed", 400, 600), "sed.py": ("crossed", 300, 600), "made.py": ("new", None, 700),
            "copied.py": ("new", None, 650), "pkg/sub/mod.ts": ("new", None, 520)})

    def test_hook_reports_once_per_session_and_again_in_a_new_session(self) -> None:
        first = self.bash("printf 'x = 2\\n%.0s' $(seq 200) >> grow.py")
        self.assertIn("grow.py (400 -> 600 lines)", first)
        self.assertIn("IS in scope", first)
        self.assertEqual(self.bash("printf 'x = 3\\n' >> grow.py"), "")              # same file, same session
        second = self.bash("python3 -c \"open('made.py', 'w').write('v = 1\\n' * 700)\"")
        self.assertIn("made.py (new, 700 lines)", second)
        self.assertNotIn("grow.py", second)
        again = self.bash("true", session="s-2")
        self.assertIn("grow.py (400 -> 601 lines)", again)
        self.assertIn("made.py (new, 700 lines)", again)

    def test_a_file_already_over_the_limit_is_reported_only_when_it_grows(self) -> None:
        self.assertEqual(self.bash("sed -i 's/^a = 1$/a = 11/' already.py"), "")     # edited, not longer
        self.assertEqual(self.bash("sed -i '1d' already.py"), "")                     # shorter
        grew = self.bash("printf 'a = 2\\n%.0s' $(seq 5) >> already.py")
        self.assertIn("already.py (900 -> 904 lines; it was already over the limit and grew)", grew)

    def test_moves_of_existing_files_are_not_new_code(self) -> None:
        self.assertEqual(self.bash("mv big.py moved.py"), "")
        self.assertEqual(self.bash("git mv already.py renamed.py"), "")
        moved_and_grown = self.bash("git mv grow.py grown.py && printf 'x = 2\\n%.0s' $(seq 150) >> grown.py")
        self.assertIn("grown.py (400 -> 550 lines)", moved_and_grown)

    def test_silent_outside_git_and_for_garbage_or_unrelated_tools(self) -> None:
        loose = self.tmp / "loose"
        loose.mkdir()
        self.assertEqual(self.bash("seq 900 | sed 's/^/x = /' > huge.py", cwd=loose), "")
        self.sh("printf 'x = 2\\n%.0s' $(seq 200) >> grow.py")
        for payload in ("not json", "[]", {"tool_name": "WebSearch", "tool_input": {"query": "x"}},
                        {"tool_name": "Bash", "tool_input": {"command": "ls"}, "cwd": "/nonexistent/x"}):
            with self.subTest(payload=payload):
                done = self.hook(payload)
                self.assertEqual((done.returncode, done.stdout, done.stderr), (0, "", ""))

    def test_absolute_paths_and_codex_workdir_reach_other_work_trees(self) -> None:
        loose = self.tmp / "loose"
        loose.mkdir()
        target = self.repo / "grow.py"
        text = self.bash(f"printf 'x = 2\\n%.0s' $(seq 200) >> {target}", cwd=loose)
        self.assertIn(f"{target} (400 -> 600 lines)", text)
        self.sh("python3 -c \"open('made.py', 'w').write('v = 1\\n' * 700)\"")
        done = self.hook({"tool_name": "Bash", "session_id": "codex", "tool_input": {
            "command": ["bash", "-lc", "python3 make.py"], "workdir": str(self.repo)}}, cwd=loose)
        self.assertIn("made.py (new, 700 lines)", json.loads(done.stdout)["hookSpecificOutput"]["additionalContext"])

    def test_an_edit_tool_warning_counts_as_reported_for_later_shell_scans(self) -> None:
        self.sh("printf 'x = 2\\n%.0s' $(seq 200) >> grow.py")
        edit = self.hook({"tool_name": "Edit", "tool_input": {"file_path": "grow.py"}})
        self.assertIn("grow.py now has 600 lines", json.loads(edit.stdout)["hookSpecificOutput"]["additionalContext"])
        self.assertEqual(self.bash("true"), "")

    def test_bounded_on_a_repository_with_many_files(self) -> None:
        files = {f"pkg{i // 500}/m{i}.py": "x = 1\n" for i in range(20000)}
        files["core.py"] = lines("c", 450)
        many = self.repository("many", files)
        self.sh("printf 'c = 1\\n%.0s' $(seq 100) >> core.py && touch pkg3/m1600.py && "
                "python3 -c \"[open(f'gen{i}.py', 'w').write('v = 1\\n' * 600) for i in range(1000)]\"", cwd=many)
        started = time.monotonic()
        done = self.hook({"tool_name": "Bash", "tool_input": {"command": "make"}}, cwd=many)
        elapsed = time.monotonic() - started
        context = json.loads(done.stdout)["hookSpecificOutput"]["additionalContext"]
        self.assertLess(elapsed, file_guard.BUDGET_SECONDS + 2, "the hook must stay inside its own budget")
        self.assertIn("more", context)                                     # the listing is capped, not 1000 names
        self.assertLess(len(context), 4000)
        state = json.loads((self.tmp / "cache" / "metodologia" / "file-guard" / "s-1.json").read_text())
        self.assertLessEqual(len(state["reported"]), file_guard.MAX_CANDIDATES)
        self.assertIn("core.py (450 -> 550 lines)", context)
        started = time.monotonic()                     # the next command looks at the rest, still within budget
        later = self.hook({"tool_name": "Bash", "tool_input": {"command": "ls"}}, cwd=many)
        self.assertLess(time.monotonic() - started, file_guard.BUDGET_SECONDS + 2)
        self.assertNotIn("core.py", later.stdout)


class SnapshotCheck(GuardCase):
    def commit_snapshot(self, command: str) -> tuple[str, str]:
        base = self.git(self.repo, "rev-parse", "HEAD")
        self.sh(command)
        self.git(self.repo, "add", "-A")
        self.git(self.repo, "commit", "-q", "-m", "snapshot")
        return base, self.git(self.repo, "rev-parse", "HEAD")

    def test_finds_crossing_new_and_grown_files_and_ignores_excluded_types(self) -> None:
        base, snap = self.commit_snapshot(
            "printf 'x = 2\\n%.0s' $(seq 200) >> grow.py && seq 700 | sed 's/^/v = /' > made.py && "
            "printf 'a = 2\\n' >> already.py && git mv big.py moved.py && "
            "sed -i 's/^s = 1$/s = 11/' sed.py && seq 3000 > package-lock.json && "
            "seq 900 | sed 's/^/x/' > api.generated.ts && mkdir -p vendor && seq 900 > vendor/lib.js && "
            "{ echo '// Code generated by sqlc. DO NOT EDIT.'; seq 900; } > queries.go")
        self.assertEqual(file_guard.snapshot_findings(self.repo, base, snap), [
            {"path": "already.py", "lines": 901, "base_lines": 900, "kind": "grew"},
            {"path": "grow.py", "lines": 600, "base_lines": 400, "kind": "crossed"},
            {"path": "made.py", "lines": 700, "base_lines": None, "kind": "new"}])
        self.assertEqual(file_guard.snapshot_findings(self.repo, base, base), [])
        note = file_guard.findings_note(file_guard.snapshot_findings(self.repo, base, snap))
        self.assertIn("grow.py (400 -> 600 lines)", note)
        self.assertEqual(file_guard.findings_note([]), "")

    def test_an_unreadable_range_raises(self) -> None:
        with self.assertRaises(RuntimeError):
            file_guard.snapshot_findings(self.repo, "0" * 40, "1" * 40)


