"""Generated provider wrappers and relay migration behavior."""
from __future__ import annotations

import os
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import bt_profiles
import bt_relay_cli


class ProfileWrapperGenerationTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(prefix="profile-wrappers-")
        self.addCleanup(self.tmp.cleanup)
        self.profile_cfg = {"provider": "claude", "env": {"CLAUDE_CONFIG_DIR": "/acct"}, "work_only": True,
                            "bin": "claude"}
        self.profiles = {"claude-work": self.profile_cfg,
                         "codex-1": {"provider": "codex", "env": {}, "work_only": False, "bin": "codex"}}
        for target, replacement in (("bt_profiles.load", lambda: self.profiles),
                                    ("bt_profiles.get", lambda pid: self.profiles[pid]),
                                    ("bt_profiles.shutil.which", lambda name: f"/usr/bin/{name}")):
            patcher = patch(target, replacement)
            patcher.start()
            self.addCleanup(patcher.stop)
        self.bin = Path(self.tmp.name) / "bin"

    def test_relay_wrapper_keeps_the_gate_and_runs_under_the_launcher(self) -> None:
        path = bt_profiles.write_wrapper("claude-work", self.bin, relay=True)
        text = path.read_text()
        lines = text.splitlines()
        gate = next(i for i, line in enumerate(lines) if "profiles gate" in line)
        run = next(i for i, line in enumerate(lines) if "relay_run.py" in line)
        self.assertLess(gate, run)
        self.assertIn('claude-work -- claude "$@"', text)
        self.assertIn("CLAUDE_CONFIG_DIR", text)
        self.assertTrue(lines[-1].startswith("exec "))
        self.assertTrue(os.access(path, os.X_OK))

    def test_plain_wrapper_keeps_provider_command_dynamic(self) -> None:
        text = bt_profiles.write_wrapper("claude-work", self.bin).read_text()
        self.assertNotIn("relay_run.py", text)
        self.assertIn('exec "claude" "$@"', text)

    def test_wrap_status_reports_and_defaults_to_dry_run(self) -> None:
        bt_profiles.write_wrapper("claude-work", self.bin)
        (self.bin / "codex-1").write_text("#!/bin/sh\necho hand made\n")
        out = bt_relay_cli.wrap_status(self.bin)
        self.assertIn("claude-work: plain wrapper", out)
        self.assertIn("--relay --dir", out)
        self.assertIn("codex-1", out)
        self.assertIn("not generated by metodologia", out)
        self.assertIn("dry run", out)
        self.assertNotIn("relay_run.py", (self.bin / "claude-work").read_text())

    def test_wrap_status_apply_regenerates_only_generated_wrappers(self) -> None:
        bt_profiles.write_wrapper("claude-work", self.bin)
        hand = self.bin / "codex-1"
        hand.write_text("#!/bin/sh\necho hand made\n")
        out = bt_relay_cli.wrap_status(self.bin, apply=True)
        self.assertIn("claude-work: regenerated", out)
        self.assertIn("relay_run.py", (self.bin / "claude-work").read_text())
        self.assertEqual(hand.read_text(), "#!/bin/sh\necho hand made\n")
        self.assertIn("already in use", bt_relay_cli.wrap_status(self.bin))
