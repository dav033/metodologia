"""The capture-time file guard of the durable runtime (REQ-030 item 8): a real lab repository, a real attempt
worktree from GitWorkspaces, the real handoff snapshot commit, and the JSONL telemetry the engine writes."""
from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))

from bt_contracts.execution import AttemptRef, OversizedFile, Prepared, RunRef, Snapshot
from bt_durable.adapters import size_guard
from bt_durable.adapters.m3 import M3Attempts, start_request
from bt_durable.adapters.telemetry import JsonlTelemetry
from bt_durable.control import frontier
from bt_durable.legacy import load_plan
from durable_support import Lab, git, task


class CaptureGuard(unittest.TestCase):
    def setUp(self):
        self.lab = Lab(backend="pgroup")
        self.addCleanup(self.lab.cleanup)
        (self.lab.repo / "core.py").write_text("c = 1\n" * 400)
        git(self.lab.repo, "add", "-A")
        git(self.lab.repo, "commit", "-q", "-m", "core")
        run = self.lab.freeze([task("T1", paths=["**"])])
        self.plan = load_plan(Path(run["plan_path"]).read_text(encoding="utf-8"), approved_sha256=run["plan_sha256"],
                              plan_id=run["plan_id"], revision=run["revision"])
        self.run_ref = RunRef.model_validate(run)
        self.telemetry = JsonlTelemetry(self.lab.state / "telemetry.jsonl")
        self.attempts = M3Attempts(root=self.lab.state / "attempts-root",
                                   repositories_for=lambda project: {"app": self.lab.repo},
                                   plan_for=lambda attempt: self.plan, driver_for=lambda project: None)
        self.attempts.telemetry = self.telemetry

    def worktree(self, number: int) -> tuple[AttemptRef, Prepared]:
        """The attempt's isolated checkout from the real workspace manager (what `prepare` allocates)."""
        attempt = AttemptRef(run=self.run_ref, task_id="T1", number=number, workflow_id=f"wf-{number}")
        spec = frontier.task(self.plan, "T1")
        request = start_request(attempt, spec, base_ref=git(self.lab.repo, "rev-parse", "HEAD"), timeout=600)
        workspaces = self.attempts.workspaces("proj")
        workspaces.check(request)
        ws = workspaces.allocate(request)
        adir = self.attempts.attempt_dir(attempt)
        return attempt, Prepared(worktree=Path(ws.path), branch=ws.branch, base_sha=ws.base_sha,
                                 repository=Path(ws.repo), attempt_dir=adir, prompt_path=adir / "prompt.txt",
                                 argv=("true",), env_file=adir / "agent.env.json", timeout_seconds=600)

    def events(self) -> list[dict]:
        return [e for e in self.telemetry.read() if e["event"] == "file_guard"]

    def test_capture_reports_crossing_and_new_files_and_emits_the_event(self):
        attempt, prepared = self.worktree(1)
        work = prepared.worktree
        with open(work / "core.py", "a", encoding="utf-8") as stream:      # any tool: here a plain file write
            stream.write("c = 2\n" * 150)
        (work / "src").mkdir()
        (work / "src" / "huge.py").write_text("v = 1\n" * 700)
        (work / "api.generated.ts").write_text("x\n" * 900)                # generated by name: ignored
        (work / "package-lock.json").write_text("{}\n" * 3000)            # lock/data: ignored
        spec = frontier.task(self.plan, "T1")
        snapshot = self.attempts.capture(attempt, prepared, spec)
        expected = (OversizedFile(path="core.py", lines=550, base_lines=400, kind="crossed"),
                    OversizedFile(path="src/huge.py", lines=700, base_lines=None, kind="new"))
        self.assertEqual(snapshot.oversized, expected)
        self.assertEqual(self.attempts.capture(attempt, prepared, spec), snapshot)    # a re-run step: same result
        dumped = snapshot.model_dump(mode="json")
        self.assertEqual(len(dumped["oversized"]), 2)
        self.assertEqual(Snapshot.model_validate(dumped), snapshot)          # the DBOS step round trip
        event = self.events()[0]
        self.assertEqual((event["count"], event["attempt_key"], event["snapshot_sha"], event["error"]),
                         (2, attempt.attempt_key, snapshot.snapshot_sha, None))
        self.assertEqual([f["path"] for f in event["files"]], ["core.py", "src/huge.py"])
        note = size_guard.note(snapshot.oversized)
        self.assertIn("core.py (400 -> 550 lines)", note)
        self.assertIn("src/huge.py (new, 700 lines)", note)

    def test_a_clean_attempt_keeps_the_old_checkpoint_shape(self):
        attempt, prepared = self.worktree(2)
        (prepared.worktree / "small.py").write_text("s = 1\n" * 20)
        snapshot = self.attempts.capture(attempt, prepared, frontier.task(self.plan, "T1"))
        self.assertEqual(snapshot.oversized, ())
        self.assertNotIn("oversized", snapshot.model_dump(mode="json"))
        self.assertNotIn("oversized", json.loads(snapshot.model_dump_json()))
        self.assertEqual(self.events()[0]["count"], 0)
        self.assertEqual(size_guard.note(snapshot.oversized), "")

    def test_an_unreadable_range_is_reported_not_fatal(self):
        attempt, _ = self.worktree(3)
        found = size_guard.check(attempt, self.lab.repo, "0" * 40, "1" * 40, self.telemetry)
        self.assertEqual(found, ())
        self.assertIn("RuntimeError", self.events()[0]["error"])

    def test_the_engine_wiring_gives_the_capturer_the_engine_telemetry(self):
        from bt_contracts.execution import Route
        from bt_durable.service import wire
        ports = wire(self.lab.engine_config(), repositories_for=lambda project: {"app": self.lab.repo},
                     driver_for=lambda project: None, routes=[Route(provider="claude", model="sonnet")],
                     runtime=object(), verifier=object())
        self.assertIs(ports.capturer.telemetry, ports.telemetry)


if __name__ == "__main__":
    unittest.main()
