"""Invoke the canonical Planner through a caller-selected local provider profile."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from pathlib import Path

import bt_profiles
from bt_core import slugify
from bt_resources import resource_root

PLANNER_AGENT = "planner"
PRIVATE_SKILLS = (
    "agents/planner/skills/socratic-elicitation/SKILL.md",
    "agents/planner/skills/wbs-dag-decomposition/SKILL.md",
    "agents/planner/skills/plan-mermaid-view/SKILL.md",
    "agents/planner/skills/adversarial-plan-review/SKILL.md",
)
DEFAULT_TIMEOUT_SECONDS = 900
CLAUDE_STDIN_PROMPT = "Use the Planner role to plan the request provided on stdin."
GENERATED_AGENT_MARKER = "generated by metodologia/scripts/install_agents.py"
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


class PlannerRuntimeError(ValueError):
    """A selected Planner runtime cannot be invoked without changing caller intent."""


@dataclass(frozen=True)
class PlannerRequest:
    project: str
    provider: str
    profile: str
    model: str
    prompt: str
    cwd: Path
    effort: str | None = None
    timeout_seconds: int = DEFAULT_TIMEOUT_SECONDS
    requirement_dir: Path | None = None
    repositories: Mapping[str, Path] | None = None


@dataclass(frozen=True)
class PreparedInvocation:
    provider: str
    profile: str
    model: str
    effort: str | None
    argv: tuple[str, ...]
    cwd: Path
    env: Mapping[str, str]
    stdin: str
    timeout_seconds: int


@dataclass(frozen=True)
class InvocationResult:
    provider: str
    profile: str
    model: str
    effort: str | None
    returncode: int
    response: str
    stderr: str


def _validate_text(value: object, name: str, *, required: bool = True) -> str | None:
    if value is None and not required:
        return None
    if not isinstance(value, str) or not value.strip() or _CONTROL_CHARS.search(value):
        raise PlannerRuntimeError(f"{name} must be a non-empty string without control characters")
    return value


def _markdown_body(source: Path) -> str:
    try:
        text = source.read_text(encoding="utf-8")
    except OSError as exc:
        raise PlannerRuntimeError(f"Planner instructions are unavailable at {source}") from exc
    if not text.startswith("---\n"):
        raise PlannerRuntimeError(f"Planner resource is missing frontmatter: {source}")
    _, separator, body = text[4:].partition("\n---\n")
    if not separator or not body.strip():
        raise PlannerRuntimeError(f"Planner resource has malformed frontmatter: {source}")
    return body.strip()


def _codex_instructions() -> str:
    root = resource_root()
    sections = ["You are the methodology Planner. Follow this role and its private resources.",
                _markdown_body(root / "agents" / "planner.md")]
    for relative in PRIVATE_SKILLS:
        source = root / relative
        sections.extend((f"## Private Planner resource: {Path(relative).parent.name}", _markdown_body(source)))
    return "\n\n".join(sections)


def _native_agent_path(provider: str, profile_spec: Mapping[str, object], home: Path) -> Path | None:
    if provider == "claude":
        env = profile_spec.get("env")
        config_dir = env.get("CLAUDE_CONFIG_DIR") if isinstance(env, dict) else None
        root = Path(str(config_dir)).expanduser() if config_dir else home / ".claude"
        return root / "agents" / f"{PLANNER_AGENT}.md"
    if provider == "antigravity":
        return home / ".gemini" / "config" / "agents" / PLANNER_AGENT / "agent.md"
    return None


def _request_prompt(request: PlannerRequest) -> str:
    sections: list[str] = []
    base = Path(request.cwd).expanduser().resolve(strict=True)
    if request.requirement_dir is not None:
        try:
            raw_requirement_dir = Path(request.requirement_dir).expanduser()
            requirement_dir = (raw_requirement_dir if raw_requirement_dir.is_absolute() else base / raw_requirement_dir)
            requirement_dir = requirement_dir.resolve(strict=True)
        except (OSError, TypeError, ValueError) as exc:
            raise PlannerRuntimeError("Requirement directory must exist") from exc
        if not requirement_dir.is_dir() or not (requirement_dir / "SPEC.md").is_file():
            raise PlannerRuntimeError("Requirement directory must contain SPEC.md")
        sections.append(f"Requirement directory:\n{requirement_dir}")

    repositories = request.repositories or {}
    if not isinstance(repositories, Mapping):
        raise PlannerRuntimeError("repositories must map workspace roles to local paths")
    if repositories:
        rows = ["Repository mappings:"]
        for role, path_value in sorted(repositories.items()):
            if not isinstance(role, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}", role):
                raise PlannerRuntimeError("repository roles must be simple workspace identifiers")
            try:
                raw_path = Path(path_value).expanduser()
                path = (raw_path if raw_path.is_absolute() else base / raw_path).resolve(strict=False)
            except (OSError, TypeError, ValueError) as exc:
                raise PlannerRuntimeError(f"Invalid path for repository role '{role}'") from exc
            if _CONTROL_CHARS.search(str(path)):
                raise PlannerRuntimeError(f"Invalid path for repository role '{role}'")
            suffix = "" if path.is_dir() else " (not present locally)"
            rows.append(f"- {role}: {path}{suffix}")
        sections.append("\n".join(rows))

    sections.append(f"User request:\n{request.prompt}")
    return "\n\n".join(sections)


def _validate_request(request: PlannerRequest, environ: Mapping[str, str] | None, *, gate_workdir: bool = True
                      ) -> tuple[Path, dict[str, str], Mapping[str, object]]:
    if request.provider not in bt_profiles.LAUNCHABLE:
        raise PlannerRuntimeError(f"Unsupported Planner provider '{request.provider}'; no provider was substituted")
    _validate_text(request.profile, "profile")
    _validate_text(request.model, "model")
    _validate_text(request.prompt, "prompt")
    _validate_text(request.effort, "effort", required=False)
    if not isinstance(request.project, str) or slugify(request.project, 60) != request.project:
        raise PlannerRuntimeError("project must be a registered project slug")
    if isinstance(request.timeout_seconds, bool) or not isinstance(request.timeout_seconds, int) or not (
            0 < request.timeout_seconds <= 86_400):
        raise PlannerRuntimeError("timeout_seconds must be an integer from 1 to 86400")

    try:
        cwd = Path(request.cwd).expanduser().resolve(strict=True)
    except (OSError, TypeError, ValueError) as exc:
        raise PlannerRuntimeError("Planner working directory must exist") from exc
    if not cwd.is_dir():
        raise PlannerRuntimeError("Planner working directory must be a directory")

    try:
        spec = bt_profiles.get(request.profile)
        actual_provider = bt_profiles.require_launchable(request.profile)
        if actual_provider != request.provider:
            raise PlannerRuntimeError(
                f"Profile '{request.profile}' selects '{actual_provider}', not '{request.provider}'; nothing was sent"
            )
        bt_profiles.authorize(request.profile, request.project)
        allowed, reason = bt_profiles.gate_cwd(request.profile, cwd) if gate_workdir else (True, "")
        if not allowed:
            raise PlannerRuntimeError(f"{reason} Nothing was sent.")
        env = bt_profiles.session_env(request.profile, request.provider,
                                      environ=dict(environ) if environ is not None else None,
                                      project=request.project)
    except bt_profiles.ProfileError as exc:
        raise PlannerRuntimeError(f"{exc} Nothing was sent.") from exc

    return cwd, env, spec


def _require_native_agent(request: PlannerRequest, spec: Mapping[str, object], home: Path) -> None:
    native_path = _native_agent_path(request.provider, spec, home)
    if native_path is None:
        return
    try:
        native_source = native_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PlannerRuntimeError(
            f"Planner agent is not installed for profile '{request.profile}' at {native_path}; "
            "run install-agents --agent planner first. Nothing was sent."
        ) from exc
    if GENERATED_AGENT_MARKER not in native_source:
        raise PlannerRuntimeError(
            f"Planner agent at {native_path} is not generated by metodologia; "
            "preserve it and resolve the profile conflict before sending. Nothing was sent."
        )


def prepare_invocation(request: PlannerRequest, *, home: Path | None = None,
                       environ: Mapping[str, str] | None = None) -> PreparedInvocation:
    """Validate the selected account and build a process request without starting a provider."""
    cwd, env, spec = _validate_request(request, environ)

    binary = spec.get("bin")
    if not isinstance(binary, str) or not binary.strip():
        raise PlannerRuntimeError(f"Profile '{request.profile}' has no provider executable; nothing was sent")
    executable = shutil.which(binary)
    if executable is None:
        raise PlannerRuntimeError(f"'{binary}' is not on PATH; install the selected CLI first. Nothing was sent.")

    selected_home = home or Path.home()
    prompt = _request_prompt(request)
    _require_native_agent(request, spec, selected_home)

    argv = [executable]
    if request.provider == "claude":
        argv.extend(("--agent", PLANNER_AGENT, "--model", request.model, "--print", CLAUDE_STDIN_PROMPT))
        if request.effort is not None:
            argv.extend(("--effort", request.effort))
        stdin = prompt
    elif request.provider == "codex":
        argv.extend(("exec", "--model", request.model))
        if request.effort is not None:
            argv.extend(("--config", f"model_reasoning_effort={json.dumps(request.effort)}"))
        argv.extend(("--config", f"developer_instructions={json.dumps(_codex_instructions(), ensure_ascii=False)}", "-"))
        stdin = prompt
    else:
        argv.extend(("--agent", PLANNER_AGENT, "--model", request.model))
        if request.effort is not None:
            argv.extend(("--effort", request.effort))
        argv.extend(("--input-format", "stream-json", "--output-format", "stream-json"))
        stdin = json.dumps({"event": "user", "message": {"content": prompt}}, ensure_ascii=False) + "\n"

    return PreparedInvocation(provider=request.provider, profile=request.profile, model=request.model,
                              effort=request.effort, argv=tuple(argv), cwd=cwd, env=env, stdin=stdin,
                              timeout_seconds=request.timeout_seconds)


def _antigravity_response(stdout: str) -> str:
    responses: list[str] = []
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        if isinstance(event, dict) and event.get("event") == "result":
            result = event.get("result")
            if (isinstance(result, dict) and result.get("status") == "SUCCESS"
                    and isinstance(result.get("response"), str)):
                responses.append(result["response"])
    return responses[-1] if responses else ""


def _antigravity_model(stdout: str) -> str:
    init_events: list[object] = []
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        if isinstance(event, dict) and event.get("event") == "init":
            init_events.append(event.get("init"))
    if len(init_events) != 1 or not isinstance(init_events[0], dict):
        raise PlannerRuntimeError("Antigravity did not report exactly one valid init event; response discarded")
    model = init_events[0].get("model")
    if not isinstance(model, str) or not model.strip():
        raise PlannerRuntimeError("Antigravity did not report the effective model; response discarded")
    return model


def _antigravity_error(stdout: str) -> str:
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        if not isinstance(event, dict) or event.get("event") != "result":
            continue
        result = event.get("result")
        if not isinstance(result, dict) or result.get("status") == "SUCCESS":
            continue
        error = result.get("error")
        if isinstance(error, str) and error:
            return error
        if error is not None:
            return json.dumps(error, ensure_ascii=False, sort_keys=True)
        return f"Antigravity returned status {result.get('status')!r}"
    return ""


def invoke(request: PlannerRequest, *, runner: Callable[..., subprocess.CompletedProcess[str]] | None = None,
           home: Path | None = None, environ: Mapping[str, str] | None = None) -> InvocationResult:
    """Start the selected provider once and return its response; failures never trigger a fallback."""
    prepared = prepare_invocation(request, home=home, environ=environ)
    run = runner or subprocess.run
    try:
        completed = run(list(prepared.argv), input=prepared.stdin, cwd=prepared.cwd,
                        env=dict(prepared.env), text=True, capture_output=True,
                        timeout=prepared.timeout_seconds, check=False)
    except subprocess.TimeoutExpired as exc:
        raise PlannerRuntimeError(f"{prepared.provider} Planner invocation timed out; no provider fallback was tried") from exc
    except OSError as exc:
        raise PlannerRuntimeError(f"Could not start {prepared.provider} Planner: {exc}") from exc

    stdout = completed.stdout if isinstance(completed.stdout, str) else ""
    stderr = completed.stderr if isinstance(completed.stderr, str) else ""
    response = _antigravity_response(stdout) if prepared.provider == "antigravity" else stdout
    if response and prepared.provider == "antigravity":
        reported_model = _antigravity_model(stdout)
        if reported_model != prepared.model:
            raise PlannerRuntimeError(
                f"Antigravity reported model {reported_model!r}, requested {prepared.model!r}; response discarded"
            )
    if prepared.provider == "antigravity" and not response:
        provider_error = _antigravity_error(stdout)
        if provider_error:
            stderr = "\n".join(part for part in (stderr, provider_error) if part)
    return InvocationResult(provider=prepared.provider, profile=prepared.profile, model=prepared.model,
                            effort=prepared.effort, returncode=completed.returncode,
                            response=response, stderr=stderr)


# --- read-only diagnostic mode: no tools, no MCP, private directory, caller-supplied deadline -------------------------

DIAGNOSTIC_REQUIRED_FLAGS = ("--tools", "--strict-mcp-config", "--mcp-config", "--setting-sources",
                             "--disable-slash-commands")
MAX_DIAGNOSTIC_OUTPUT_BYTES = 1024 * 1024


class UnsupportedDiagnosticSandbox(PlannerRuntimeError):
    """The runtime cannot be proven to run with an empty tool list and no MCP/connectors."""


@dataclass(frozen=True)
class DiagnosticResult:
    provider: str
    profile: str
    model: str
    effort: str | None
    returncode: int
    stdout: bytes
    stderr: str
    argv: tuple[str, ...]


def probe_diagnostic_sandbox(provider: str, executable: str, env: Mapping[str, str], cwd: Path, *,
                             runner: Callable[..., subprocess.CompletedProcess] | None = None) -> None:
    """Prove the CLI can enforce an allowlist (not a denylist) of zero tools and strict MCP; raise otherwise."""
    if provider != "claude":
        raise UnsupportedDiagnosticSandbox(
            f"unsupported_diagnostic_sandbox: no-tools/MCP denial is not enforceable for provider '{provider}'")
    try:
        done = (runner or subprocess.run)([executable, "--help"], env=dict(env), cwd=cwd, capture_output=True,
                                          text=True, timeout=30, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise UnsupportedDiagnosticSandbox(f"unsupported_diagnostic_sandbox: capability probe failed: {exc}") from exc
    help_text = (done.stdout or "") + (done.stderr or "")
    missing = [flag for flag in DIAGNOSTIC_REQUIRED_FLAGS if flag not in help_text]
    if done.returncode != 0 or missing:
        raise UnsupportedDiagnosticSandbox(
            f"unsupported_diagnostic_sandbox: CLI lacks {', '.join(missing) or 'a working --help'}")


def invoke_diagnostic(request: PlannerRequest, private_dir: Path, *,
                      runner: Callable[..., subprocess.CompletedProcess] | None = None,
                      probe_runner: Callable[..., subprocess.CompletedProcess] | None = None,
                      home: Path | None = None, environ: Mapping[str, str] | None = None) -> DiagnosticResult:
    """Run the Planner role once with an empty tool allowlist, no MCP and only `private_dir` as workspace.

    `request.cwd` is ignored in favour of `private_dir`; the prompt carries all the evidence. No fallback, no retry.
    """
    private = Path(private_dir).resolve(strict=True)
    scoped = PlannerRequest(project=request.project, provider=request.provider, profile=request.profile,
                            model=request.model, prompt=request.prompt, cwd=private, effort=request.effort,
                            timeout_seconds=request.timeout_seconds)
    _, env, spec = _validate_request(scoped, environ, gate_workdir=False)  # empty private dir; project authorized above
    binary = spec.get("bin")
    executable = shutil.which(binary) if isinstance(binary, str) and binary.strip() else None
    if executable is None:
        raise PlannerRuntimeError(f"Profile '{request.profile}' provider executable is unavailable. Nothing was sent.")
    probe_diagnostic_sandbox(request.provider, executable, env, private, runner=probe_runner)
    _require_native_agent(scoped, spec, home or Path.home())
    # `--setting-sources project` hides the user's agents, and the private directory is the only project there is: the generated
    # (marker-checked) Planner agent is made available there, as the project agent the CLI looks for (found with the real CLI)
    native = _native_agent_path(request.provider, spec, home or Path.home())
    if native is not None and request.provider == "claude":
        project_agent = private / ".claude" / "agents" / native.name
        project_agent.parent.mkdir(parents=True, exist_ok=True)
        project_agent.write_text(native.read_text(encoding="utf-8"), encoding="utf-8")
    mcp_config = private / "mcp-empty.json"
    mcp_config.write_text('{"mcpServers": {}}', encoding="utf-8")
    argv = [executable, "--agent", PLANNER_AGENT, "--model", request.model, "--print", CLAUDE_STDIN_PROMPT,
            "--tools", "", "--strict-mcp-config", "--mcp-config", str(mcp_config),
            "--setting-sources", "project", "--disable-slash-commands", "--output-format", "text"]
    if request.effort is not None:
        argv.extend(("--effort", request.effort))
    try:
        done = (runner or subprocess.run)(argv, input=_request_prompt(scoped).encode("utf-8"), cwd=private,
                                          env=dict(env), capture_output=True, timeout=request.timeout_seconds,
                                          check=False)
    except subprocess.TimeoutExpired as exc:
        raise PlannerRuntimeError(f"{request.provider} diagnostic timed out; no retry was made") from exc
    except OSError as exc:
        raise PlannerRuntimeError(f"Could not start {request.provider} diagnostic: {exc}") from exc
    out = done.stdout if isinstance(done.stdout, bytes) else str(done.stdout or "").encode("utf-8")
    err = done.stderr.decode("utf-8", "replace") if isinstance(done.stderr, bytes) else str(done.stderr or "")
    return DiagnosticResult(provider=request.provider, profile=request.profile, model=request.model,
                            effort=request.effort, returncode=done.returncode,
                            stdout=out[:MAX_DIAGNOSTIC_OUTPUT_BYTES + 1], stderr=err[-2000:], argv=tuple(argv))
