"""`bitacora.py relay <action>` dispatch and the explicit hook installer."""
from __future__ import annotations

import json
import os
import shlex
import sys
from pathlib import Path

import bt_relay as relay
from bt_core import PYTHON, SCRIPT

HOOK_EVENTS = ("UserPromptSubmit", "PostToolUse", "Stop")


def hook_command() -> str:
    return f'"{PYTHON}" "{SCRIPT}" hook relay'


def hook_json() -> dict:
    entry = {"hooks": [{"type": "command", "command": hook_command(), "timeout": 8}]}
    return {"hooks": {event: [entry] for event in HOOK_EVENTS}}


def _has_relay(entries) -> bool:
    return isinstance(entries, list) and any(
        isinstance(e, dict) and isinstance(e.get("hooks"), list)
        and any(isinstance(h, dict) and h.get("command") == hook_command() for h in e["hooks"]) for e in entries)


def install(settings: Path | None, dry_run: bool) -> str:
    """Merge the relay hooks into `settings` (idempotent, atomic, `.bak` kept once). Without a path, or with
    --dry-run, only prints."""
    wanted = hook_json()
    if settings is None or dry_run:
        return json.dumps(wanted, indent=2) + (f"\n(dry run: {settings} not modified)" if settings else "")
    settings = settings.resolve()  # a symlinked settings.json stays a symlink: the real file is replaced
    current = json.loads(settings.read_text(encoding="utf-8")) if settings.exists() else {}
    if not isinstance(current, dict) or not isinstance(current.get("hooks", {}), dict):
        raise SystemExit(f"{settings}: unexpected structure (hooks must be an object); nothing changed")
    hooks = current.setdefault("hooks", {})
    for event, entries in wanted["hooks"].items():
        if not isinstance(hooks.get(event, []), list):
            raise SystemExit(f"{settings}: hooks.{event} is not a list; nothing changed")
        if not _has_relay(hooks.get(event)):
            hooks.setdefault(event, []).extend(entries)
    mode = settings.stat().st_mode & 0o777 if settings.exists() else 0o600
    backup = settings.with_suffix(settings.suffix + ".bak")
    if settings.exists() and not backup.exists():
        backup.write_text(settings.read_text(encoding="utf-8"), encoding="utf-8")
        backup.chmod(mode)
    tmp = settings.with_name(f"{settings.name}.{os.getpid()}.tmp")
    tmp.write_text(json.dumps(current, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    tmp.chmod(mode)
    tmp.replace(settings)
    return f"relay hooks installed in {settings}"


def wrap_status(directory: Path, apply: bool = False) -> str:
    """Which launcher wrappers already run the agent under relay_run.py, and the exact commands for the others.
    Dry run unless `apply`; a wrapper not generated by metodologia is never touched."""
    import bt_profiles
    lines = []
    for pid, spec in sorted(bt_profiles.load().items()):
        if spec.get("provider") not in ("claude", "codex"):
            continue
        path = directory / pid
        if not path.is_file():
            lines.append(f"{pid}: no wrapper in {directory}")
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "relay_run.py" in text:
            lines.append(f"{pid}: relay wrapper already in use")
        elif "generated by metodologia" not in text:
            lines.append(f"{pid}: {path} was not generated by metodologia; left alone")
        else:
            command = (f"{shlex.quote(PYTHON)} {shlex.quote(str(SCRIPT))} profiles wrapper {shlex.quote(pid)} --relay "
                       f"--dir {shlex.quote(str(directory))}")
            if apply:
                lines.append(f"{pid}: regenerated {bt_profiles.write_wrapper(pid, directory, relay=True)}")
            else:
                lines.append(f"{pid}: plain wrapper. To switch: {command}")
    return "\n".join(lines) + ("" if apply else "\n(dry run: nothing changed; pass --apply or run the commands)")


def filter_mux_env(text: str | None) -> dict:
    """Only the whitelisted multiplexer variables survive into the helper's environment."""
    import bt_relay_client
    try:
        raw = json.loads(text or "{}")
    except ValueError:
        return {}
    allowed = {v for _, extra in bt_relay_client.MUX_VARS.values() for v in extra}
    return {k: v for k, v in (raw.items() if isinstance(raw, dict) else []) if k in allowed and isinstance(v, str)}


def dispatch(a) -> None:
    if a.action == "install":
        print(install(Path(a.settings).expanduser() if a.settings else None, a.dry_run))
    elif a.action == "handoff":
        import bt_relay_handoff
        summary = sys.stdin.read()
        print(bt_relay_handoff.handoff(summary, a.session, a.to, a.cwd, force=a.force))
    elif a.action == "launch":
        import bt_relay_launch
        if not a.handoff or not a.to:
            sys.exit("relay launch needs --handoff and --to")
        mux_env = filter_mux_env(a.mux_env)
        bt_relay_launch.run(Path(a.handoff), a.to, a.cwd, a.session or "unknown", a.mux, a.target, a.pid, a.start,
                            a.exit_current != "0", mux_env=mux_env,
                            wrapper=(a.wrapper_pid, a.wrapper_start) if a.wrapper_pid and a.wrapper_start else None)
    elif a.action == "wrap-status":
        print(wrap_status(Path(a.dir).expanduser() if a.dir else Path.home() / ".local" / "bin", a.apply))
    elif a.action == "cancel":
        import bt_relay_launch
        print(bt_relay_launch.cancel())
    else:
        print(json.dumps({"settings": relay.settings(), "pending": relay.load_json(relay.relay_dir() / "pending.json", {})},
                         indent=1))
